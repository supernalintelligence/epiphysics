'use client';

import { useState } from 'react';
import Link from 'next/link';
import record from './observatory-demo.json';
import CollectionStatus from './CollectionStatus';
import s from './ResearchExperience.module.css';

export default function ObservatoryExample() {
  const [message, setMessage] = useState('');
  const download = () => {
    const url = URL.createObjectURL(new Blob([JSON.stringify(record, null, 2) + '\n'], { type: 'application/json' }));
    const a = document.createElement('a'); a.href = url; a.download = 'epiphysics-synthetic-example.json'; a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    setMessage('Example record downloaded.');
  };
  const share = async () => {
    try { await navigator.clipboard.writeText(`${window.location.origin}/observatory`); setMessage('Link copied.'); }
    catch { setMessage('Copy this page’s address to share the example.'); }
  };
  return <div className={s.site}><div className={s.container}>
    <div className={s.topline}><Link href="/">Epiphysics</Link><span>Observatory</span></div>
    <div className={s.recordHeader}><h1 className={s.title}>Observatory</h1><p className={s.lead}>Collection status and reproducible examples from the research engine.</p></div>
    <CollectionStatus />
    <div className={s.recordHeader}>
      <h2 className={s.title}>A forecast, from source to score</h2>
      <p className={s.lead}>A small example of the record we want every experiment to leave: its inputs, prediction, outcome, and calculation.</p>
    </div>
    <p className={s.notice}>This example uses fictional workers and a simulated clock. Both probabilities are chosen by hand. It demonstrates the software; it is not a test of predictive skill.</p>
    <div className={s.timeline}>
      <section className={s.entry}>
        <div className={s.entryTime}>10:00 UTC<span>Evidence saved</span></div>
        <div><h2>Two workers and a queue</h2><blockquote>Worker A has two pending jobs. Worker B supplies data.</blockquote><p>The collector saves these bytes. A snapshot identifies this version of the source, so later edits cannot silently replace the input used by a prediction.</p><dl><dt>Source</dt><dd>synthetic:worker-queue</dd><dt>Representation</dt><dd>Two entities; a directed “supplies data” relationship from B to A.</dd></dl></div>
      </section>
      <section className={s.entry}>
        <div className={s.entryTime}>10:00 UTC<span>Forecast recorded</span></div>
        <div><h2>Will Worker A finish its queued jobs?</h2><p>The baseline assigns a 50% probability. A second, illustrative method assigns 70%. They use the same question and evidence snapshot.</p><dl><dt>Deadline</dt><dd>10:05 UTC</dd><dt>Resolution time</dt><dd>10:10 UTC or later</dd><dt>Resolution rule</dt><dd>The completion record reports zero pending jobs.</dd></dl></div>
      </section>
      <section className={s.entry}>
        <div className={s.entryTime}>10:11 UTC<span>Outcome saved</span></div>
        <div><h2>The queue is empty</h2><blockquote>Worker A has zero pending jobs.</blockquote><p>The outcome is “yes,” recorded as 1. The original source and this revision both remain in the ledger. A later correction would be a new record linked to this one.</p></div>
      </section>
    </div>
    <section className={s.section}>
      <h2>Calculating the error</h2>
      <p className={s.intro}>For a binary outcome, the Brier score is (probability − outcome)². Lower values mean less error. Here, (0.5 − 1)² = 0.25 and (0.7 − 1)² = 0.09.</p>
      <table className={s.table}><caption className={s.fine}>One synthetic question · scores generated by the engine</caption><thead><tr><th scope="col">Method</th><th scope="col">Resolved</th><th scope="col">Brier score</th></tr></thead><tbody>{Object.entries(record.scores.methods).map(([name, m]) => <tr key={name}><th scope="row">{name === 'baseline' ? 'Constant baseline' : 'Illustrative representation'}</th><td>{m.resolved}</td><td>{m.brier.toFixed(2)}</td></tr>)}</tbody></table>
      <p className={s.intro}>The second number is lower because we chose a probability closer to the invented outcome. A real comparison needs many future questions, the same evidence, declared costs, and all failures included.</p>
      <div className={s.actions}><button className={s.primary} onClick={download}>Download the record</button><button className={s.secondary} onClick={share}>Copy link</button><span role="status" className={s.fine}>{message}</span></div>
    </section>
    <section className={s.closing}>
      <h2>Reproduce this example</h2>
      <p className={s.intro}>From the repository root with Python 3.10 or later, choose an empty store and a new output filename:</p>
      <pre className={s.code}><code>{'PYTHONPATH=engine python3 -m epiphysics \\\n  --store engine/.data/my-demo demo \\\n  --output engine/.data/my-demo-export.json\n\nPYTHONPATH=engine python3 -m epiphysics \\\n  --store engine/.data/my-demo verify'}</code></pre>
      <p className={s.fine}>The generated example contains {record.integrity.events} linked records and uses the simulated date 24 November 2026. The export includes event metadata and source hashes; the local store also holds the original source bytes.</p>
      <details className={s.details}><summary>View all records</summary><pre className={s.code}>{JSON.stringify(record, null, 2)}</pre></details>
      <p className={s.intro}>The hash chain checks local integrity. An independent timestamp witness is still needed to support a claim that a commitment existed before a deadline. Neither mechanism establishes that a source is true or the archive complete.</p>
      <Link className={s.secondary} href="/experiments/prospective-observatory">Prospective evaluation protocol</Link>
    </section>
  </div></div>;
}
